// Builds the mini program's line-icon set from the pinned `lucide-static`
// dev dependency. The same SVGs feed two outputs so code and Figma stay in step:
//   miniprogram/styles/icons.wxss  inline SVG masks, coloured by `color`
//   docs/design/icons.json         plain SVG markup for the Figma library
// Usage: node scripts/build-icons.mjs [--check]
