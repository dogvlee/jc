const WXSS_OUT = path.join(projectRoot, 'miniprogram', 'styles', 'icons.wxss');
const JSON_OUT = path.join(projectRoot, 'docs', 'design', 'icons.json');

function innerMarkup(name) {
  const file = path.join(packageRoot, 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide-static@${version} 中没有图标：${name}`);
  const source = fs.readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const body = source.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!body) throw new Error(`无法解析图标：${name}`);
  return body[1]
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .replace(/currentColor/g, '#000')
    .replace(/"/g, "'")
    .trim();
}

function svg(name, color) {
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='${color}' `
    + `stroke-width='${STROKE_WIDTH}' stroke-linecap='round' stroke-linejoin='round'>`
    + `${innerMarkup(name).replace(/#000/g, color)}</svg>`;
}

function dataUri(markup) {
  return `data:image/svg+xml,${markup.replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}`;
}

export function renderIcons() {
  const header = `/* Generated by scripts/build-icons.mjs from lucide-static@${version} (ISC; see THIRD_PARTY_NOTICES). Do not edit. */\n`;
  // The glyph is painted with the current text colour through an alpha mask,
  // so `color` recolours an icon and `font-size` sizes it.
  const base = '.icon { display: inline-block; flex: none; width: 1em; height: 1em; vertical-align: -0.14em; '
    + 'background-color: currentColor; -webkit-mask-repeat: no-repeat; -webkit-mask-position: center; '
    + '-webkit-mask-size: 100% 100%; }\n';
  const rules = ICON_NAMES
    .map((name) => `.icon-${name} { -webkit-mask-image: url("${dataUri(svg(name, '#000'))}"); }`)
    .join('\n');
  const icons = Object.fromEntries(ICON_NAMES.map((name) => [name, svg(name, '#1F2329')]));
  return {
    wxss: `${header}${base}${rules}\n`,
    json: `${JSON.stringify({ source: 'lucide-static', version, license: 'ISC', strokeWidth: STROKE_WIDTH, icons }, null, 2)}\n`
  };
}

// core.autocrlf checkouts turn the generated LF files into CRLF on Windows.
export function isCurrent(file, text) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const outputs = renderIcons();
  const targets = [[WXSS_OUT, outputs.wxss], [JSON_OUT, outputs.json]];
  if (process.argv.includes('--check')) {
    const stale = targets.filter(([file, text]) => !isCurrent(file, text));
    if (stale.length) {
      console.error(`图标产物已过期，请运行 npm run build:icons：${stale.map(([file]) => path.relative(projectRoot, file)).join(', ')}`);
      process.exit(1);
    }
    console.log(`[icons] ${ICON_NAMES.length} icons up to date`);
  } else {
    for (const [file, text] of targets) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
    }
    console.log(`[icons] wrote ${ICON_NAMES.length} icons (lucide-static@${version}, stroke ${STROKE_WIDTH})`);
  }
}
