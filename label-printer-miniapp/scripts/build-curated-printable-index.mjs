// Records which printer families can print each curated template as it is
// designed, so the public shelf never offers a template that no supported
// printer can print. Rerun after changing curated recipes, sizes or profiles.
//   miniprogram/app/curated/printable-index.js
// Usage: node scripts/build-curated-printable-index.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');

export const INDEX_PATH = path.join(projectRoot, 'miniprogram', 'app', 'curated', 'printable-index.js');

const HEADER = [
  '// Generated by scripts/build-curated-printable-index.mjs: run `npm run curated:printable`',
  '// after changing curated recipes or printer profiles. Printers that print each template',
  '// as designed: 5 = 58mm, 8 = 80mm, 58 = both. Templates that no supported printer can',
  '// print are left out, so the shelf never offers them.'
];

/** [[templateId, '5' | '8' | '58' | ''], ...] in library order. */
export function printableFamilies() {
  const { CURATED_INDEX, buildCuratedDocument } = require('../miniprogram/app/curated/index.js');
  const { printableProfilesForDocument, printerFamilyCode } = require('../miniprogram/core/profiles.js');
  return CURATED_INDEX.map((entry) => [
    entry.id,
    printerFamilyCode(printableProfilesForDocument(buildCuratedDocument(entry.id)))
  ]);
}

export function renderPrintableIndex(families = printableFamilies()) {
  const rows = families
    .filter(([, code]) => code)
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([id, code]) => `  '${id}': '${code}'`);
  return `${HEADER.join('\n')}\nmodule.exports = {\n${rows.join(',\n')}\n};\n`;
}

// core.autocrlf checkouts turn the generated LF file into CRLF on Windows.
export function isCurrent(file, text) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text;
}

function summary(families) {
  const count = (test) => families.filter(([, code]) => test(code)).length;
  const shelf = count((code) => code);
  return `${shelf} of ${families.length} curated templates printable `
    + `(58mm: ${count((code) => code.includes('5'))}, 80mm: ${count((code) => code.includes('8'))}, `
    + `both: ${count((code) => code === '58')}); ${families.length - shelf} left off the shelf`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  if (!fs.existsSync(INDEX_PATH)) {
    if (check) {
      console.error('缺少 miniprogram/app/curated/printable-index.js，请运行 npm run curated:printable');
      process.exit(1);
    }
    // The curated library reads this file on load, so a first run starts from an empty map.
    fs.writeFileSync(INDEX_PATH, 'module.exports = {};\n');
  }
  const families = printableFamilies();
  const text = renderPrintableIndex(families);
  if (check) {
    if (!isCurrent(INDEX_PATH, text)) {
      console.error('可打印模板索引已过期，请运行 npm run curated:printable');
      process.exit(1);
    }
    console.log(`[curated] up to date: ${summary(families)}`);
  } else {
    fs.writeFileSync(INDEX_PATH, text);
    console.log(`[curated] wrote ${path.relative(projectRoot, INDEX_PATH)}: ${summary(families)}`);
  }
}
