#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const researchDir = path.join(root, 'research', 'online-templates');
const rawDir = path.join(researchDir, 'raw');
const indexPath = path.join(researchDir, 'index.json');
const outPath = path.join(root, 'src', 'app', 'online-templates-pack.js');
const { importNiimTemplate } = require(path.join(root, 'src', 'core', 'niim-template-import'));
const ACCENTS = ['#E85D4C','#2F6FED','#1B8A5A','#0E7C86','#3D5A80','#E09F3E','#C1121F','#6B5B95','#457B9D','#E76F51','#0077B6','#2A9D8F','#4A6FA5','#264653','#118AB2','#F4A261','#40916C'];
function mapCategory(name) {
  const n = String(name || '');
  if (/药|医|医院|胃管|输液|药品/.test(n)) return { category: '生活', industry: '实用功能' };
  if (/仓|库|货架|物流|快递|运单|排号/.test(n)) return { category: '仓储', industry: '行业标识' };
  if (/线|缆|工位|资产|办公|Wi-?Fi|名片/.test(n)) return { category: '办公', industry: '行业标识' };
  if (/国网|电力|表号|台区|实验室|样品/.test(n)) return { category: '行业', industry: '行业标识' };
  if (/价|商品|零售|珠宝|服装|烘焙|促销|净菜|花店|酸奶/.test(n)) return { category: '零售', industry: '内容设计' };
  if (/日期|食品|效期|植物|婚礼|姓名|家居|收纳/.test(n)) return { category: '生活', industry: '实用功能' };
  return { category: '线上', industry: '行业模板' };
}
function detectKindFromDoc(doc) {
  const types = (doc.elements || []).map((e) => e.type);
  if (types.includes('barcode')) return 'barcode';
  if (types.includes('qrcode')) return 'qr';
  return 'accent';
}
function hash(s) { let h = 0; for (let i = 0; i < s.length; i++) h = ((h << 5) - h + s.charCodeAt(i)) | 0; return h; }
function packItem(meta, raw) {
  const w = Number(raw.width || meta.width) || 40;
  const h = Number(raw.height || meta.height) || 30;
  raw.width = w; raw.height = h;
  if (!raw.name) raw.name = meta.name || '线上模板';
  const { document, meta: importMeta } = importNiimTemplate(raw);
  document.widthMm = w; document.heightMm = h; document.name = raw.name;
  const sx = w / Math.max(1, importMeta.width);
  const sy = h / Math.max(1, importMeta.height);
  if (Math.abs(sx - 1) > 0.01 || Math.abs(sy - 1) > 0.01) {
    for (const el of document.elements) {
      el.x *= sx; el.y *= sy; el.width *= sx; el.height *= sy;
      if (el.fontSize) el.fontSize = Math.max(1.6, el.fontSize * Math.min(sx, sy));
    }
  }
  for (const el of document.elements) {
    el.width = Math.max(0.5, Math.min(el.width, w));
    el.height = Math.max(0.5, Math.min(el.height, h));
    el.x = Math.max(0, Math.min(el.x, w - el.width));
    el.y = Math.max(0, Math.min(el.y, h - el.height));
  }
  const cats = mapCategory(raw.name);
  const kind = detectKindFromDoc(document);
  const id = 'online-' + String(meta.id);
  const accent = ACCENTS[Math.abs(hash(id)) % ACCENTS.length];
  return { id, name: String(raw.name), size: [w, h], category: cats.category, industry: cats.industry, kind, badge: '线上', blurb: 'NIIM 线上行业模板 · ' + w + 'x' + h, accent, document, source: 'online-niim', thumbnailUrl: meta.thumbnail || raw.thumbnail || raw.previewImage || '', uses: 50 + (Math.abs(hash(id)) % 200) };
}
function main() {
  const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
  const pack = []; const errors = [];
  for (const meta of index) {
    const rawPath = path.join(rawDir, meta.id + '.json');
    if (!fs.existsSync(rawPath)) { errors.push({ id: meta.id, error: 'missing raw' }); continue; }
    try {
      const raw = JSON.parse(fs.readFileSync(rawPath, 'utf8'));
      const item = packItem(meta, raw);
      if (!item.document || !item.document.elements || !item.document.elements.length) { errors.push({ id: meta.id, error: 'empty elements' }); continue; }
      pack.push(item);
    } catch (err) { errors.push({ id: meta.id, error: String(err && err.message || err) }); }
  }
  const parts = [];
  parts.push('/**');
  parts.push(' * Offline pack of NIIMBOT public industry templates.');
  parts.push(' * Generated by scripts/build-online-templates-pack.js - do not hand-edit.');
  parts.push(' * Source: research/online-templates/raw/*.json');
  parts.push(' */');
  parts.push('');
  parts.push('const ONLINE_TEMPLATES = ' + JSON.stringify(pack, null, 2) + ';');
  parts.push('');
  parts.push('function getOnlineTemplate(id) {');
  parts.push('  return ONLINE_TEMPLATES.find((item) => item.id === id) || null;');
  parts.push('}');
  parts.push('');
  parts.push('function buildOnlineDocument(id) {');
  parts.push('  const item = getOnlineTemplate(id);');
  parts.push('  if (!item) return null;');
  parts.push('  return JSON.parse(JSON.stringify(item.document));');
  parts.push('}');
  parts.push('');
  parts.push('module.exports = {');
  parts.push('  ONLINE_TEMPLATES,');
  parts.push('  getOnlineTemplate,');
  parts.push('  buildOnlineDocument');
  parts.push('};');
  parts.push('');
  fs.writeFileSync(outPath, parts.join(String.fromCharCode(10)), 'utf8');
  const report = { packCount: pack.length, errors, outPath, bytes: fs.statSync(outPath).size };
  fs.writeFileSync(path.join(researchDir, 'pack-report.json'), JSON.stringify(report, null, 2), 'utf8');
  console.log(JSON.stringify(report, null, 2));
}
main();
